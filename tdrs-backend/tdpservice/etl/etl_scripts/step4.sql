CREATE OR REPLACE TEMPORARY VIEW report4 AS
SELECT
  RPT_MONTH_YEAR,
  OVER60M,
  COUNT(*) AS freq
FROM
  TLcases
WHERE
  --FIPS = FIPS
  OVER60M >= 1 AND
  --In the SAS cript, it's NHOH_REC > 1, but NHOH_REC is binary so I think it should be this instead ...

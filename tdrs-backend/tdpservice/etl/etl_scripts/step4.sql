--CREATE REPORT 'TANF CASES WITH OVER 60 MONTHS ASSISTANCE IN FY20&FY.'--
CREATE OR REPLACE TEMPORARY VIEW report3 AS
SELECT
  RPT_MONTH_YEAR AS MONTH,
  STRATUM,
  MONTHS_FED_TIME_LIMIT,
  CASE_ID,
  SUM(TLEX1),
  SUM(TLEX2),
  SUM(TLEX3),
  SUM(TLEX4),
  SUM(TLEX6),
  SUM(TLEX7),
  SUM(TLEX8),
  SUM(TLEX9)
FROM
  TLcases
WHERE
  OVER60M >= 1
GROUP BY
  RPT_MONTH_YEAR,
  STRATUM,
  MONTHS_FED_TIME_LIMIT,
  CASE_ID;


CREATE OR REPLACE TEMPORARY VIEW family AS
SELECT
  FIPS_CODE,
  CASE_NUMBER AS CASE_ID,
  REGION,
  STRATUM,
  FUNDING_STREAM AS FUNDING,
  FAMILY_TYPE AS TYPE_FAM,
  FAMILY_EXEMPT_TIME_LIMITS AS FEXMPT_TL,
  RPT_MONTH_YEAR
FROM
  read_files(
		'/Volumes/ofa_sandbox/legacy_code/input/TANF_T1_DataSurge_2025-09-10-084149.csv',
		format => 'csv',
		header => 'true',
		sep => ','
	);

CREATE OR REPLACE TEMPORARY VIEW adult AS
SELECT
  FIPS_CODE,
  CASE_NUMBER AS CASE_ID,
  FAMILY_AFFILIATION,
  NONCUSTODIAL_PARENT,
  -- ADULT_AGE in the SAS code but this should still work
  AGE_FIRST AS AGE_1,
  MARITAL_STATUS,
  RELATIONSHIP_HOH,
  MONTHS_FED_TIME_LIMIT,
  RPT_MONTH_YEAR
FROM
	read_files(
		'/Volumes/ofa_sandbox/legacy_code/input/TANF_T2_DataSurge_2025-09-10-084149.csv',
		format => 'csv',
		header => 'true',
		sep => ','
	);

CREATE OR REPLACE TEMPORARY VIEW combo1 AS
SELECT
  family.*,
  adult.* EXCEPT (FIPS_CODE, CASE_ID, RPT_MONTH_YEAR)
  -- flag for RELATIONSHIP_HOH in (1,2) to be summed in future step
  --RELATIONSHIP_HOH in (1,2) AS RELATIONSHIP_HOH_FLAG,
  -- flag for RELATIONSHIP_HOH in (1,2) and FAMILY_AFFILIATION = 1 to be summed in future step
  --RELATIONSHIP_HOH in (1,2) AND FAMILY_AFFILIATION = 1 AS RELATIONSHIP_HOH_FAMILY_AFFILIATION_FLAG
FROM
  family
  INNER JOIN adult ON
    family.FIPS_CODE = adult.FIPS_CODE AND
    family.RPT_MONTH_YEAR = adult.RPT_MONTH_YEAR AND
    family.CASE_ID = adult.CASE_ID;

-- calculate some summary variables when are later merged into the original dataset --

CREATE OR REPLACE TEMPORARY VIEW combo2 AS
SELECT
  --*,
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID,
  SUM(FAMILY_AFFILIATION) AS NADULT,
  SUM(CASE WHEN RELATIONSHIP_HOH IN (1,2) THEN 1 ELSE 0 END) AS NHOH,
  SUM(CASE WHEN RELATIONSHIP_HOH IN (1,2) AND FAMILY_AFFILIATION = 1 THEN 1 ELSE 0 END) AS NHOH_REC
FROM combo1
GROUP BY
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID;

CREATE OR REPLACE TEMPORARY VIEW combo3 AS
SELECT
  combo1.*,
  combo2.* EXCEPT (FIPS_CODE, RPT_MONTH_YEAR, CASE_ID),
  CASE
    WHEN RELATIONSHIP_HOH IN (1,2) THEN 1
    ELSE 2
  END AS AHEAD
FROM
  combo1
  INNER JOIN combo2 ON
    combo1.FIPS_CODE = combo2.FIPS_CODE AND
    combo1.RPT_MONTH_YEAR = combo2.RPT_MONTH_YEAR AND
    combo1.CASE_ID = combo2.CASE_ID;

CREATE OR REPLACE TEMPORARY VIEW combo4 AS
WITH CTA AS (
  SELECT
    *,
    ROW_NUMBER() OVER (PARTITION BY CASE_ID ORDER BY FIPS_CODE, RPT_MONTH_YEAR, CASE_ID, RELATIONSHIP_HOH, MONTHS_FED_TIME_LIMIT DESC, NHOH_REC DESC) AS ROWNUM
  FROM
    combo3
)
SELECT
  *
FROM
  CTA
WHERE
  ROWNUM = 1
ORDER BY
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID,
  RELATIONSHIP_HOH,
  MONTHS_FED_TIME_LIMIT DESC,
  NHOH_REC DESC;

CREATE OR REPLACE TEMPORARY VIEW combo5 AS
SELECT
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID,
  SUM(CASE WHEN MONTHS_FED_TIME_LIMIT <= 0 THEN 1 ELSE 0 END) AS CM_0,
  SUM(CASE WHEN 0<MONTHS_FED_TIME_LIMIT AND MONTHS_FED_TIME_LIMIT<=12 THEN 1 ELSE 0 END) AS CM01_12,
  SUM(CASE WHEN 12<MONTHS_FED_TIME_LIMIT AND MONTHS_FED_TIME_LIMIT<=24 THEN 1 ELSE 0 END) AS CM13_24,
  SUM(CASE WHEN 24<MONTHS_FED_TIME_LIMIT AND MONTHS_FED_TIME_LIMIT<=36 THEN 1 ELSE 0 END) AS CM25_36,
  SUM(CASE WHEN 36<MONTHS_FED_TIME_LIMIT AND MONTHS_FED_TIME_LIMIT<=48 THEN 1 ELSE 0 END) AS CM37_48,
  SUM(CASE WHEN 48<MONTHS_FED_TIME_LIMIT AND MONTHS_FED_TIME_LIMIT<=59 THEN 1 ELSE 0 END) AS CM49_59,
  SUM(CASE WHEN MONTHS_FED_TIME_LIMIT = 60 THEN 1 ELSE 0 END) AS CM60,
  SUM(CASE WHEN MONTHS_FED_TIME_LIMIT>60 THEN 1 ELSE 0 END) AS OVER60M
FROM
  combo4
GROUP BY
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID;

CREATE OR REPLACE TEMPORARY VIEW combo6 AS
SELECT
  combo4.*,
  combo5.* EXCEPT (FIPS_CODE, RPT_MONTH_YEAR, CASE_ID)
FROM
  combo4
  INNER JOIN combo5 ON
    combo4.FIPS_CODE = combo5.FIPS_CODE AND
    combo4.RPT_MONTH_YEAR = combo5.RPT_MONTH_year AND
    combo4.CASE_ID = combo5.CASE_ID;


CREATE OR REPLACE TEMPORARY VIEW combo7 AS
SELECT
  *,
  CASE
    WHEN (NHOH > 0) AND (FEXMPT_TL NOT IN (1,2,3,4,5,6,7,8,9) OR (FEXMPT_TL = 1 AND MONTHS_FED_TIME_LIMIT > 60)) THEN "1"
    WHEN (NHOH > 0) AND (FEXMPT_TL = 2 AND NHOH_REC > 0) THEN "2"
    WHEN (NHOH > 0) AND (FEXMPT_TL = 3 AND FUNDING != 2) THEN "3"
    WHEN (NHOH > 0) AND (FEXMPT_TL = 6 AND FUNDING != 2) THEN "3"
    WHEN (NHOH > 0) AND (FEXMPT_TL IN (7,8) AND MONTHS_FED_TIME_LIMIT <= 60) THEN "5"
    WHEN (NHOH > 0) AND (FEXMPT_TL = 9 AND MONTHS_FED_TIME_LIMIT <= 60) THEN "5"
    ELSE " "
  END AS TLERRFG,
  CASE
    WHEN (NHOH > 0 AND FEXMPT_TL NOT IN (1,2,3,4,5,6,7,8,9) OR (FEXMPT_TL = 1 AND MONTHS_FED_TIME_LIMIT > 60)) AND (MONTHS_FED_TIME_LIMIT <= 60) AND NOT (FUNDING = 2) THEN 1
    WHEN (NHOH > 0) AND (FEXMPT_TL = 2 AND NHOH_REC > 0) AND (MONTHS_FED_TIME_LIMIT <= 60) THEN 1
    WHEN (NHOH > 0) AND (FEXMPT_TL NOT IN (1,2,3,4,5,6,7,8,9) OR (FEXMPT_TL = 1 AND MONTHS_FED_TIME_LIMIT > 60)) AND (MONTHS_FED_TIME_LIMIT <= 60) AND (FUNDING = 2) THEN 3
    WHEN (NHOH > 0) AND NOT (FEXMPT_TL NOT IN (1,2,3,4,5,6,7,8,9) OR (FEXMPT_TL = 1 AND MONTHS_FED_TIME_LIMIT > 60)) AND (MONTHS_FED_TIME_LIMIT <= 60) AND (FUNDING = 2) THEN 6
    WHEN (NHOH > 0) AND NOT (FEXMPT_TL NOT IN (1,2,3,4,5,6,7,8,9) OR (FEXMPT_TL = 1 AND MONTHS_FED_TIME_LIMIT > 60)) AND (MONTHS_FED_TIME_LIMIT <= 60) AND NOT (FUNDING = 2) THEN 7
    WHEN (NHOH > 0) AND (FEXMPT_TL = 2 AND NHOH_REC > 0) AND (MONTHS_FED_TIME_LIMIT > 60) THEN 7
    WHEN (NHOH > 0) AND (FEXMPT_TL = 3 AND FUNDING != 2) AND (MONTHS_FED_TIME_LIMIT <= 60) THEN 1
    WHEN (NHOH > 0) AND (FEXMPT_TL = 3 AND FUNDING != 2) AND (MONTHS_FED_TIME_LIMIT > 60) THEN 7
    WHEN (NHOH > 0) AND (FEXMPT_TL = 6 AND FUNDING != 2) AND (MONTHS_FED_TIME_LIMIT > 60) THEN 7
    WHEN (NHOH > 0) AND (FEXMPT_TL = 6 AND FUNDING != 2) AND (MONTHS_FED_TIME_LIMIT <= 60) THEN 1
    WHEN (NHOH > 0) AND (FEXMPT_TL = 4 AND MONTHS_FED_TIME_LIMIT > 60) THEN 9
    WHEN (NHOH > 0) AND (FEXMPT_TL IN (7,8) AND MONTHS_FED_TIME_LIMIT > 60) THEN 1
    WHEN (NHOH > 0) AND (FEXMPT_TL = 9 AND MONTHS_FED_TIME_LIMIT <= 60) THEN 4
    ELSE FEXMPT_TL
  END AS TLEXM
FROM
  combo6;


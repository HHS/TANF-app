--CREATE REPORT 'MONTHS OF TANF FAMILIIES RECEIVED ASSISTANCE REPORTED IN FY20&FY.' --
CREATE OR REPLACE TEMPORARY VIEW report8 AS
SELECT
  RPT_MONTH_YEAR AS MONTH,
  SUM(SAMP) AS FAMILIES, --'Families',
  SUM(NADULT) AS ADULTS, --'# of Adults',
  SUM(NHOH) AS NUMHoHS, --'# of HoHs',
  SUM(NHOH_REC) AS NUMHoHRecipients, --'# of HoH recipients',
  SUM(CM_0) AS CM_0, --'0 MONTH',
  SUM(CM01_12) AS CM01_12, --'1~12 months',
  SUM(CM13_24) AS CM13_24, --'13~24 months',
  SUM(CM25_36) AS CM25_36, --'25~36 months',
  SUM(CM37_48) AS CM37_48, --'37~48 months',
  SUM(CM49_59) AS CM49_59, --'49~59 months',
  SUM(CM60) AS CM60, --'60 months',
  SUM(OVER60M) AS OVER60M --'60+ months'
FROM
  TLcases3
GROUP BY
  RPT_MONTH_YEAR;



CREATE OR REPLACE TEMPORARY VIEW TLcases2 AS
SELECT
  *,
  CASE
    WHEN CASE_ID IS NULL THEN 0
    ELSE 1
  END AS SAMP
FROM
  TLcases
WHERE
  RPT_MONTH_YEAR IS NOT NULL;


--CREATE REPORT 'TANF CASES WITH OVER 60 MONTHS IN FY20&FY.'--

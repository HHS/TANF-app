--CREATE REPORT 'TANF TIMELIMIT ERRORFLAGS IN FY20&FY.'--
CREATE OR REPLACE TEMPORARY VIEW report1 AS
SELECT
  RPT_MONTH_YEAR AS MONTH,
  TLERRFG,
  COUNT(*) AS freq
FROM
  combo7
GROUP BY
  RPT_MONTH_YEAR,
  TLERRFG;

--CREATE REPORT 'TANF CASES REPORTED WITH TIME-LIMIT ERRORS IN FY20&FY.'--
CREATE OR REPLACE TEMPORARY VIEW report2 AS
SELECT
  RPT_MONTH_YEAR AS MONTH,
  TYPE_FAM,
  FUNDING,
  TLERRFG,
  FEXMPT_TL,
  FAMILY_AFFILIATION,
  RELATIONSHIP_HOH,
  NHOH_REC,
  MONTHS_FED_TIME_LIMIT
FROM
  combo7;

CREATE OR REPLACE TEMPORARY VIEW TLcases1 AS
SELECT
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID,
  SUM(CASE WHEN TLEXM = 1 THEN 1 ELSE 0 END) AS TLEX1,
  SUM(CASE WHEN TLEXM = 2 THEN 1 ELSE 0 END) AS TLEX2,
  SUM(CASE WHEN TLEXM = 3 THEN 1 ELSE 0 END) AS TLEX3,
  SUM(CASE WHEN TLEXM = 4 THEN 1 ELSE 0 END) AS TLEX4,
  SUM(CASE WHEN TLEXM = 5 THEN 1 ELSE 0 END) AS TLEX5,
  SUM(CASE WHEN TLEXM = 6 THEN 1 ELSE 0 END) AS TLEX6,
  SUM(CASE WHEN TLEXM = 7 THEN 1 ELSE 0 END) AS TLEX7,
  SUM(CASE WHEN TLEXM = 8 THEN 1 ELSE 0 END) AS TLEX8,
  SUM(CASE WHEN TLEXM = 9 THEN 1 ELSE 0 END) AS TLEX9
FROM
  combo7
GROUP BY
  FIPS_CODE,
  RPT_MONTH_YEAR,
  CASE_ID;

CREATE OR REPLACE TEMPORARY VIEW TLcases AS
SELECT
  combo7.*,
  TLcases1.* EXCEPT (FIPS_CODE, RPT_MONTH_YEAR, CASE_ID)
FROM
  combo7
  INNER JOIN TLcases1 ON
    combo7.FIPS_CODE = TLcases1.FIPS_CODE AND
    combo7.RPT_MONTH_YEAR = TLcases1.RPT_MONTH_year AND
    combo7.CASE_ID = TLcases1.CASE_ID;


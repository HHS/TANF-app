CREATE OR REPLACE TEMPORARY VIEW stat2 AS
SELECT
	monthly1.*,
	monthly2.* EXCEPT (FIPS_CODE),
	monthly3.* EXCEPT (FIPS_CODE),
	monthly4.* EXCEPT (FIPS_CODE),
	monthly5.* EXCEPT (FIPS_CODE),
	monthly6.* EXCEPT (FIPS_CODE),

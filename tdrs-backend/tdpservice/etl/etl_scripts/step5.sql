	monthly1 INNER JOIN
	monthly2 ON monthly1.FIPS_CODE = monthly2.FIPS_CODE INNER JOIN
	monthly3 ON monthly1.FIPS_CODE = monthly3.FIPS_CODE INNER JOIN
	monthly4 ON monthly1.FIPS_CODE = monthly4.FIPS_CODE INNER JOIN

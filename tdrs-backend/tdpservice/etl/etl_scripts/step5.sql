CREATE OR REPLACE TEMPORARY VIEW combo AS
SELECT
	*
FROM
	old;

CREATE OR REPLACE TEMPORARY VIEW file1 AS
SELECT
	FIPS_CODE,
	RPT_MONTH_YEAR,
	SUM(WNGAGED) AS ANGAGED,
	SUM(WN_WEI) AS AN_WEI,
	SUM(WWRK_WEI) AS AWRK_WEI,
	SUM(WNSAMP) AS ANSAMP,
	SUM(WNWORK) AS ANWORK,
	SUM(WNDCARD1) AS ANDCARD1,
	SUM(WNDCARD2) AS ANDCARD2,
	SUM(WNDCARD5) AS ANDCARD5,
	SUM(WNLIM_VOC) AS ANLIM_VOC,
	SUM(WNLIM_SSA) AS ANLIM_SSA,
	SUM(WNLIM_EDE) AS ANLIM_EDE,
	SUM(WNDCRD_PART) AS ANDCRD_PART,
	SUM(WTPSAMP) AS ATPSAMP,
	SUM(WTPWORK) AS ATPWORK,
	SUM(WTPLIM_VOC) AS ATPLIM_VOC,
	SUM(WTPLIMIT) AS ATPLIMIT,
	SUM(WTPDABLE) AS ATPDABLE,
	SUM(WTPNCP) AS ATPNCP,
	SUM(WTPDCARD2) AS ATPDCARD2,
	SUM(WTPDCARD5) AS ATPDCARD5,
	SUM(WNDVEXEM) AS AFDVEXEM,
	SUM(WTPDVEXEM) AS TPDVEXEM,
	SUM(WTPDCRD_PART) AS ATPDCRD_PART,
	SUM(WNSAMP) - SUM(WNDCARD1) - SUM(WNDCARD2) - SUM(WNDCARD5) AS AFDEN,
	SUM(WNSAMP) - SUM(WNDCARD1) - SUM(WNDCARD2) - SUM(WNDCARD5) - SUM(WNDVEXEM) AS AFADJDEN,
	SUM(WTPSAMP) - SUM(WTPDCARD2) - SUM(WTPDCARD5) - SUM(WTPNCP) - SUM(WTPDABLE) AS TPDEN,
	SUM(WTPSAMP) - SUM(WTPDCARD2) - SUM(WTPDCARD5) - SUM(WTPNCP) - SUM(WTPDABLE) - SUM(WTPDVEXEM) AS TPADJDEN,
	SUM(WNLIM_VOC) + SUM(WNLIM_SSA) + SUM(WNLIM_EDE) AS AFTOTLIM,
	SUM(WTPLIM_VOC) + SUM(WTPLIMIT) AS ATPTOTLIM--,
	--CASE
	--	WHEN SUM(WNWORK) > (SUM(WNLIM_VOC) + SUM(WNLIM_SSA) + SUM(WNLIM_EDE)) AND (SUM(WNLIM_VOC) + SUM(WNLIM_SSA) + SUM(WNLIM_EDE)) > 0.3 * SUM(WNWORK) THEN (SUM(WNWORK) - (SUM(WNLIM_VOC) + SUM(WNLIM_SSA) + SUM(WNLIM_EDE))) / 0.7
	--	ELSE ANWORK
	--END AS ADJNUM
FROM
	combo
WHERE
	FIPS_CODE IS NOT NULL AND
	RPT_MONTH_YEAR IS NOT NULL
GROUP BY
	FIPS_CODE,
	RPT_MONTH_YEAR;

-- ADJNUM (adjusted number) represented when _______  --

CREATE OR REPLACE TEMPORARY VIEW file2 AS
SELECT
	*,
	CASE
		WHEN ANWORK > AFTOTLIM AND AFTOTLIM > (0.3 * ANWORK) THEN (ANWORK - AFTOTLIM)/0.7
		ELSE ANWORK
	END AS ADJNUM,
	CASE
		WHEN ATPWORK > ATPTOTLIM AND ATPTOTLIM > (0.3 * ATPWORK) THEN (ATPWORK - ATPTOTLIM) / 0.7
		ELSE ATPWORK
	END AS ADJTPNUM
FROM
	file1;


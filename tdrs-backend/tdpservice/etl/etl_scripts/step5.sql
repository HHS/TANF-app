	monthly9.* EXCEPT (FIPS_CODE),
	monthly10.* EXCEPT (FIPS_CODE),
	monthly11.* EXCEPT (FIPS_CODE),
	monthly12.* EXCEPT (FIPS_CODE),
	(CASE WHEN ANSAMP_JAN > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_FEB > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_MAR > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_APR > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_MAY > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_JUN > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_JUL > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_AUG > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_SEP > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_OCT > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_NOV > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN ANSAMP_DEC > 0 THEN 1 ELSE 0 END) AS MTHS,
	(CASE WHEN TPDEN_JAN > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_FEB > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_MAR > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_APR > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_MAY > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_JUN > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_JUL > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_AUG > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_SEP > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_OCT > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_NOV > 0 THEN 1 ELSE 0 END) +
	(CASE WHEN TPDEN_DEC > 0 THEN 1 ELSE 0 END) AS TPMTHS

CREATE OR REPLACE TEMPORARY VIEW stsumfl2 AS
SELECT
  *,
  AFLIM_VOC + AFLIM_SSA + AFLIM_EDE AS AFLIMIT,
  ATPLIM_VOC + ATPLIMIT AS ATPTOTLIM,
  AFSAMP - (AFDCARD1 + AFDCARD2 + AFDCARD5) + ANDCRD_PART AS AF_DENUM,
  ATPSAMP - (ATPDCARD2 + ATPDCARD5 + ATPNCP + ATPDABLE) + ATPDCRD_PART AS TP_DENUM,
  (AFSAMP - (AFDCARD1 + AFDCARD2 + AFDCARD5) + ANDCRD_PART) - AFDVEXEM AS AF_ADJD,
  (ATPSAMP - (ATPDCARD2 + ATPDCARD5 + ATPNCP + ATPDABLE) + ATPDCRD_PART) - ATPDVEXEM AS ATP_ADJD,
  CASE
    WHEN (AFLIM_VOC + AFLIM_SSA + AFLIM_EDE) > (0.3 * AFNWORK) and (AFNWORK > (AFLIM_VOC + AFLIM_SSA + AFLIM_EDE)) THEN (AFNWORK - (AFLIM_VOC + AFLIM_SSA + AFLIM_EDE)) / (0.7)
    ELSE 0
  END AS AFLIMWK,
  CASE
    WHEN (ATPLIM_VOC + ATPLIMIT) > (0.3 * ATPWORK)  and (ATPWORK > (ATPLIM_VOC + ATPLIMIT)) THEN (ATPWORK - (ATPLIM_VOC + ATPLIMIT)) / (0.7)
    ELSE 0
  END AS ATPLIMWK
FROM
  stsumfl1;

CREATE OR REPLACE TEMPORARY VIEW stsumfl AS
SELECT
  *,
  CASE
    WHEN AFLIMWK > 0 THEN AFLIMWK
    ELSE AFNWORK
  END AS AF_ADJN,
  CASE
    WHEN ATPLIMWK > 0 THEN ATPLIMWK
    ELSE ATPWORK
  END AS ATP_ADJN
FROM
  stsumfl2;


-- first, we determine the number of adults by FIPS_CODE and STRATUM for a given RPT_MONTH_YEAR --

CREATE OR REPLACE TEMPORARY VIEW s1 AS
SELECT
  FIPS_CODE,
  RPT_MONTH_YEAR,
  STRATUM,
  COUNT(DISTINCT CASE_NUMBER) AS COUNT
FROM
	read_files(
		'/Volumes/ofa_sandbox/legacy_code/input/TANF_T1_DataSurge_2025-09-10-084149.csv',
		format => 'csv',
		header => 'true',
		sep => ','
	)
WHERE
	RPT_MONTH_YEAR = ym
GROUP BY
  FIPS_CODE,
  RPT_MONTH_YEAR,
  STRATUM;

-- next, we determine the number of families (called CASES) for each FIPS_CODE for a given RPT_MONTH_YEAR --

CREATE OR REPLACE TEMPORARY VIEW s2 AS
SELECT
  FIPS_CODE,
  RPT_MONTH_YEAR,
  NUM_FAMILIES as CASES
FROM
  read_files(
		'/Volumes/ofa_sandbox/legacy_code/input/TANF_T6_DataSurge_2025-09-10-084149.csv',
		format => 'csv',
		header => 'true',
		sep => ','
	)
WHERE
	RPT_MONTH_YEAR = ym;

-- then, we determine the number of cases ... I'm not sure how s3 is different from s2

CREATE OR REPLACE TEMPORARY VIEW s3 AS
SELECT
	FIPS_CODE,
	FAMILIES_MONTH as CASES,
	STRATUM,
	RPT_MONTH_YEAR
FROM
  read_files(
		'/Volumes/ofa_sandbox/legacy_code/input/TANF_T7_DataSurge_2025-09-10-084149.csv',
		format => 'csv',
		header => 'true',
		sep => ','
	)
WHERE
  TDRS_SECTION_IND = 1 AND
  FAMILIES_MONTH > 0 AND
	RPT_MONTH_YEAR = ym;


CREATE OR REPLACE TEMPORARY VIEW weight1 AS
SELECT
  s1.FIPS_CODE,
  s1.RPT_MONTH_YEAR,
  s1.STRATUM,
  s1.COUNT,
  CASE
      WHEN s1.FIPS_CODE = 72 AND s1.STRATUM = 2 THEN 0
      WHEN s3.CASES IS NULL THEN s2.CASES
      WHEN s3.CASES IS NOT NULL AND s1.COUNT > s3.CASES then s1.COUNT
      WHEN s3.CASES IS NULL AND s1.COUNT > s2.CASES then s1.COUNT
      ELSE s3.CASES
  END AS CASES
FROM
	s1
    FULL JOIN
    s2
    ON
      s1.FIPS_CODE = s2.FIPS_CODE AND
      s1.RPT_MONTH_YEAR = s2.RPT_MONTH_YEAR
    FULL JOIN
    s3
    ON
      s1.FIPS_CODE = s3.FIPS_CODE AND
      s1.RPT_MONTH_YEAR = s3.RPT_MONTH_YEAR AND
      s1.STRATUM = s3.STRATUM;

-- double check this logic - there are some rows with many counts, but no cases ... --

-- print this out as weight2025.09 into a folder called WGTLIB --

CREATE OR REPLACE TEMPORARY VIEW weight AS
SELECT
  *,
  CASES/COUNT as WGHT
FROM
	weight1
WHERE
  FIPS_CODE IS NOT NULL AND
  CASES != 0;




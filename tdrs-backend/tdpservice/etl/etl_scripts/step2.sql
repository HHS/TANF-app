CREATE OR REPLACE TEMPORARY VIEW allsumfl AS
SELECT
  *,
  -- the function try_divide returns NULL if the denominator is NULL --
  round(100 * try_divide(AFNWORK, AF_DENUM), 0.1) AS AF_PRATE,
  round(100 * try_divide(AFLIMWK, AF_DENUM), 0.1) AS AF_LRATE,
  round(100 * try_divide(AF_ADJN, AF_DENUM), 0.1) AS AF_ARATE,
  round(100 * try_divide(ATPWORK, TP_DENUM), 0.1) AS TP_PRATE,
  round(100 * try_divide(ATPLIMWK, TP_DENUM), 0.1) AS TP_LRATE,
  round(100 * try_divide(ATP_ADJN, TP_DENUM), 0.1) AS TP_ARATE,
  round(100 * try_divide(AF_ADJN, AF_ADJD), 0.1) AS AF_VRATE,
  round(100 * try_divide(ATP_ADJN, ATP_ADJD), 0.1) AS TP_VRATE
  -- also some variables are renamed, but I think that might need to be done later because they have variables in the names
FROM
  stsumfl;



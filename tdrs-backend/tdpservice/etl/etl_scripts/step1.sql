	*,
	-- NWORK_D_WPS means that a person can be included in the WPR, but only for specific conditions, which are described in the above step (NDEEM15, NDEEM16, or NDEEM17)
	CASE
		WHEN (NDEEM15 = 1 OR NDEEM16 = 1 OR NDEEM17 = 1) AND NWORK_ND = 0 AND NWORK_D_CSWE = 0 THEN 1
		ELSE 0
	END AS NWORK_D_WPS
FROM

-- Step 10: Merge the two dataframes for each parent into one --
----------------------------------------------------------------

-- First, we merge the two datasets (pf_2p1 and pf_2p2) so we can look at each family's two parents simultaneously --
-- We also calculate the required core hours and required total hours (TP_REQCORE and TP_REQALL), which are used to determine work partipation --
-- We also calculate their hours without deeming any hours (TPHRS_ND, TPOHRS_ND, and TPTHRS_ND) --

CREATE OR REPLACE TEMPORARY VIEW final_2p1 AS
SELECT
	pf_2p1.*,
	pf_2p2.* EXCEPT (FIPS_CODE, CASE_ID, FAMILY_TYPE, FTYPE, IS2P, N_WEI, YOUNGEST, NDISABLE, NDCARD2, NDCRD_PART, NSAMP),
	1 AS TPSAMP,
	-- required core hours --
	CASE
		WHEN NOT (RECEIVES_SUB_CC = 1 AND AMT_SUB_CC > 0) OR (RECEIVES_SUB_CC = 1 AND (P1_WORK_PART_STATUS = '08' OR P2_WORK_PART_STATUS = '08')) THEN 30
		ELSE 50
	END AS TP_REQCORE,
	-- required total hours --
	CASE
		WHEN NOT (RECEIVES_SUB_CC = 1 AND AMT_SUB_CC > 0) OR (RECEIVES_SUB_CC = 1 AND (P1_WORK_PART_STATUS = '08' OR P2_WORK_PART_STATUS = '08')) THEN 35
		ELSE 55
	END AS TP_REQALL,
	-- core hours before deeming --
	P1_HRS_WRK + P2_HRS_WRK AS TPHRS_ND,
	-- non-core hours before deeming --
	P1_OHRS_WRK + P2_OHRS_WRK AS TPOHRS_ND,
	-- total hours before deeming --
	P1_THRS_WRK + P2_THRS_WRK AS TPTHRS_ND
FROM
	pf_2p1
	INNER JOIN pf_2p2
	ON pf_2p1.FIPS_CODE = pf_2p2.FIPS_CODE AND pf_2p1.CASE_ID = pf_2p2.CASE_ID;

-- the subsequent tables build upon each other to calculate various financial and demographic variables --

-- first, we want to see if each family can be included in work partipation rate calculations without deeming any hours (TPWORK_ND = 1)
-- for non-qualifying families, we can deem hours in later steps. We calculate TPCWEHRs, which will be used to adjust their required hours later --

CREATE OR REPLACE TEMPORARY VIEW final_2p2 AS
SELECT
	*,
	-- TPWORK is used to calculate work rate --
	-- First, we see if TPWORK can be applied WITHOUT deeming any hours (TPWORK_ND)
	CASE
		WHEN TPHRS_ND >= TP_REQCORE AND TPTHRS_ND >= TP_REQALL THEN 1
		ELSE 0
	END AS TPWORK_ND,
	-- TPCSWEHRS is used to help deem hours later if TPWORK_ND is 0 --
	-- TPCSWEHRS is essentially the sum of other hours related to working (such as hours spend searching for jobs) --
	CASE
		WHEN NOT (TPHRS_ND >= TP_REQCORE AND TPTHRS_ND >= TP_REQALL) THEN P1_CSWE_HRS + P2_CSWE_HRS
		ELSE 0
	END AS TPCSWEHRS
FROM
	final_2p1;

-- For parents that do NOT qualify, we can deem their hours to see if they qualify for work participation later on. --
-- First, we determine if we can reduce their hours needed to qualify for WPR --
CREATE OR REPLACE TEMPORARY VIEW final_2p3 AS
SELECT
	*,
	-- recalculate the two-parent core deem hours by subtracting CSWE hours from required core hours if certain conditions are met --
	CASE
		WHEN TPWORK_ND = 0 AND (TPHRS_ND < TP_REQCORE) AND (FLSA_STATE = 1) AND (TPCSWEHRS > 0) AND (TPCSWEHRS >= FLOOR((CASH_AMOUNT + CC_AMOUNT + OTHER_AMOUNT + TRANSITION_SERVICES_AMOUNT + TRANSP_AMOUNT + AMT_FOOD_STAMP_ASSISTANCE - CHILD_SUPPORT_AMT)/(5*MIN_WAGES))) THEN TP_REQCORE - TPCSWEHRS
		ELSE 0
	END AS TPCORDMHRS,
	-- TPDEEMCOR tracks if deemed hours were necessary for a family to count in work participation rates --
	CASE
		WHEN TPWORK_ND = 0 AND (TPHRS_ND < TP_REQCORE) AND (FLSA_STATE = 1) AND (TPCSWEHRS > 0) AND (TPCSWEHRS >= FLOOR((CASH_AMOUNT + CC_AMOUNT + OTHER_AMOUNT + TRANSITION_SERVICES_AMOUNT + TRANSP_AMOUNT + AMT_FOOD_STAMP_ASSISTANCE - CHILD_SUPPORT_AMT)/(5*MIN_WAGES))) THEN 1
		ELSE 0
	END AS TPDEEMCOR
FROM
	final_2p2;

CREATE OR REPLACE TEMPORARY VIEW final_2p4 AS
SELECT
	*,
  -- TPHRS if we had to deem some hours
	CASE
		WHEN TPDEEMCOR = 1 THEN TPHRS_ND + TPCORDMHRS
		ELSE 0
	END AS TPHRS_D_CSWE,
	-- TPTHRS if we had to deem some hours
	CASE
		WHEN TPDEEMCOR = 1 THEN TPTHRS_ND + TPCORDMHRS
		ELSE 0
	END AS TPTHRS_D_CSWE
    FROM
    	final_2p3;



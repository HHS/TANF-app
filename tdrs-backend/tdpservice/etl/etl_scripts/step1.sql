		ELSE 0
	END AS NWORK_D_CSWE,
	-- DCOR_PART is just used for tracking purposes. It represents if a person is deemed to participate and included in the WPR calculations --
	CASE
		WHEN ISWEI = 1 AND HRS_WRK_D_CSWE >= 20 AND THRS_WRK_D_CSWE >= 30 AND NDEEMCOR = 1 THEN 1
		ELSE 0
	END AS DCOR_PART
FROM
	a3;

CREATE OR REPLACE TEMPORARY VIEW a5 AS

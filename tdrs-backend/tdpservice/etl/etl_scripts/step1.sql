# # PART 1 : CREATING TAN
#
# The first part of this project is to create the dataframe tan&ym (where &ym represents the year and month that the data was collected). This dataframe will be used in subsequent steps to create weighted and unweighted TANF reports, as well as time-limit reports.
#
# Of particular interest is the Work Participation Rate (WPR), which is a measure of each state's TANF recipients participation in the workforce. Significant parts of this script involve determining which adults can be included in the WPR.
#
# The base requirement for an adult to be included in the WPR is at least 20 hours of "core" work per week AND at least 30 hours of total ("core" plus "non-core") work per week for a single person. In families with at least two parents, these threshholds change to 50 hours of "core" work and 55 hours of total work for both parents combined. In certain circumstances (which are noted in the code below), these requirements can be lowered, which allows more adults to qualify for work participation.
#
# Additionally, there are certain conditions where we can "deem" hours for those who don't meet these requirements so they can be included in the WPR despite not meeting the hour threshhold. There are three ways to "deem" hours:
# 1. We can add CSWE hours to a family's "core" hours if they are in an FLSA state and [financial condition]
# 2. For teen parents in two-parent families, we are able to deem hours if they have satisfactory school attendance, or
# 3. For teen parents in two-parent families, we can also deem hours if they are enrolled in education directly related to employment.


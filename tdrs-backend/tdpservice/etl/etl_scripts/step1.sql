	-- calculate error flags - add notes later on what each of these represent --
	CASE
		WHEN FTYPE IN (1,2) AND FAMILY_TYPE = 1 AND N_WEI = 0 THEN '02'
		WHEN FTYPE IN (1,2) AND ((N_WEI >= 2 AND IS2P = 1) OR YOUNGEST > 1) AND AF_WORK_PART_STATUS = 1 THEN '03'
		WHEN FTYPE IN (1,2) AND AF_WORK_PART_STATUS = 15 AND NOT ((AF_AGE BETWEEN 12 AND 20) AND (AF_RELATIONSHIP_HOH IN (1,2)) AND ((AF_SCHOOL_ATTENDENCE_HOP + AF_SCHOOL_ATTENDENCE_EA + AF_SCHOOL_ATTENDENCE_HOL) > 0))THEN '04'

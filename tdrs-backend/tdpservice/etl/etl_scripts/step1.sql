CREATE OR REPLACE TEMPORARY VIEW a7 AS
SELECT
	*,
	-- NLIM_VOC represents if a person's vocational education is less than or equal to 30% of their total hours. This is used to help calculate HOLDER --
	CASE
		WHEN HWK_VOC > 0 AND HWK_VOC < 20 THEN 1
		WHEN ((NWORK_ND = 1) OR (NWORK_D_CSWE = 1) OR (NWORK_D_WPS = 1)) AND (HRS_WRK_1 + AF_NCORHRS - VOCATIONAL_ED_TRAINING_HOP - VOCATIONAL_ED_TRAINING_HOL - VOCATIONAL_ED_TRAINING_EA) > 0 AND (HRS_WRK_1 + AF_NCORHRS - VOCATIONAL_ED_TRAINING_HOP - VOCATIONAL_ED_TRAINING_HOL - VOCATIONAL_ED_TRAINING_EA) < 20 THEN 1
		-- Account for when HRS_WRK_1 has deemed hours --
		WHEN ((NWORK_ND = 1) OR (NWORK_D_CSWE = 1) OR (NWORK_D_WPS = 1)) AND (HRS_WRK_D_CSWE + AF_NCORHRS - VOCATIONAL_ED_TRAINING_HOP - VOCATIONAL_ED_TRAINING_HOL - VOCATIONAL_ED_TRAINING_EA) > 0 AND (HRS_WRK_D_CSWE + AF_NCORHRS - VOCATIONAL_ED_TRAINING_HOP - VOCATIONAL_ED_TRAINING_HOL - VOCATIONAL_ED_TRAINING_EA) < 20 THEN 1
		ELSE 0
	END AS NLIM_VOC,
  -- NDVEXEM (domestic violence exemption) is used to help calculate HOLDER --
	CASE
		WHEN ((NWORK_ND = 0) AND (NWORK_D_CSWE = 0) AND (NWORK_D_WPS = 0)) AND WORK_PART_STATUS = 9 THEN 1
		ELSE 0
	END AS NDVEXEM,
  --NDCARD1, NDCARD2, NDCARD5 mean that work requirement was met, but they are being discarded later --
	CASE
		-- the following conditions after NWORK = 1 are NDCARD1, NDCARD2, and NDCARD5 respectively --
		-- NDCARD1, NDCARD2, NDCARD5 are reset after NDCRD_PART becomes 1 --
		WHEN ((NWORK_ND = 1) OR (NWORK_D_CSWE = 1) OR (NWORK_D_WPS = 1)) AND ((WORK_PART_STATUS = 1 AND (YOUNGEST >= 0 AND YOUNGEST <= 1) AND PARENT = 2) OR (WORK_PART_STATUS = 2 AND FAMILY_AFFILIATION IN (1,2) AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0 AND (WEI >= 1 AND WEI <= 5)) OR (WORK_PART_STATUS = 5)) THEN 0
		WHEN WORK_PART_STATUS = 1 AND (YOUNGEST >= 0 AND YOUNGEST <= 1) AND PARENT = 2 THEN 1
		ELSE 0
	END AS NDCARD1,
	CASE
		-- the following conditions after NWORK = 1 are NDCARD1, NDCARD2, and NDCARD5 respectively --
		-- NDCARD1, NDCARD2, NDCARD5 are reset after NDCRD_PART becomes 1 --
		WHEN ((NWORK_ND = 1) OR (NWORK_D_CSWE = 1) OR (NWORK_D_WPS = 1)) AND ((WORK_PART_STATUS = 1 AND (YOUNGEST >= 0 AND YOUNGEST <= 1) AND PARENT = 2)  OR (WORK_PART_STATUS = 2 AND FAMILY_AFFILIATION IN (1,2) AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0 AND (WEI >= 1 AND WEI <= 5)) OR (WORK_PART_STATUS = 5)) THEN 0
		WHEN WORK_PART_STATUS = 2 AND FAMILY_AFFILIATION IN (1,2) AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0 AND (WEI >= 1 AND WEI <= 5) THEN 1
		ELSE 0
	END AS NDCARD2,
	CASE
		-- the following conditions after NWORK = 1 are NDCARD1, NDCARD2, and NDCARD5 respectively --
		-- NDCARD1, NDCARD2, NDCARD5 are reset after NDCRD_PART becomes 1 --
		WHEN ((NWORK_ND = 1) OR (NWORK_D_CSWE = 1) OR (NWORK_D_WPS = 1)) AND ((WORK_PART_STATUS = 1 AND (YOUNGEST >= 0 AND YOUNGEST <= 1) AND PARENT = 2) OR (WORK_PART_STATUS = 2 AND FAMILY_AFFILIATION IN (1,2) AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0 AND (WEI >= 1 AND WEI <= 5)) OR (WORK_PART_STATUS = 5)) THEN 0
		WHEN WORK_PART_STATUS = 5 THEN 1
		ELSE 0
	END AS NDCARD5,
	CASE
		WHEN (NWORK_ND = 1) OR (NWORK_D_CSWE = 1) OR (NWORK_D_WPS = 1) THEN 1
		ELSE 0
	END AS NWORK
FROM
	a6;

CREATE OR REPLACE TEMPORARY VIEW a8 AS
SELECT
	*,
	CASE
		-- the following conditions after NWORK = 1 are NDCARD1, NDCARD2, and NDCARD5 respectively --
		WHEN (NWORK = 1) AND ((WORK_PART_STATUS = 1 AND (YOUNGEST >= 0 AND YOUNGEST <= 1) AND PARENT = 2) OR (WORK_PART_STATUS = 2 AND FAMILY_AFFILIATION IN (1,2) AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0 AND (WEI >= 1 AND WEI <= 5)) OR (WORK_PART_STATUS = 5)) THEN 1
		ELSE 0
	END AS NDCRD_PART,
  -- HOLDER is used to determine the adults included in a family. The two adults with the highest holder values are counted as the parents of a family --
	-- If an adult is not a WEI, HOLDER is set to NULL to match the SAS results. It might be better to remove all non-WEIs from the dataset at an earlier point instead later, after the QC process iS finalized --
	CASE
		WHEN ISWEI != 1 THEN NULL
		ELSE (1000 * NWORK) + 100 * (NDCARD1 + NDCARD2 * 2 + NDCARD5 * 5) - 10 * NLIM_VOC - NDVEXEM
	END AS HOLDER
FROM
	a7;


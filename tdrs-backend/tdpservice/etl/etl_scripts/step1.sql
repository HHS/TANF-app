		WHEN (P1_WORK_PART_STATUS IN (15,16) OR P2_WORK_PART_STATUS IN (15,16)) THEN (P1_SCHOOL_ATTENDENCE_HOP + P1_SCHOOL_ATTENDENCE_HOL + P1_SCHOOL_ATTENDENCE_EA)
		ELSE 0

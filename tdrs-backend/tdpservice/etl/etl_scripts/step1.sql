		WHEN ISWEI = 1 AND AGE > 12 AND AGE < 20 AND RELATIONSHIP_HOH IN (1,2) AND (ED_NO_HIGH_SCHOOL_DIPL_HOP + ED_NO_HIGH_SCHOOL_DIPL_EA + ED_NO_HIGH_SCHOOL_DIPL_HOL) >= 20 THEN 1
		ELSE 0
	END AS NDEEM16,
  -- NDEEM17 means ____________________
  CASE
		WHEN ISWEI = 1 AND WORK_PART_STATUS = 17 AND YOUNGEST >= 0 AND YOUNGEST <= 6 AND (HRS_WRK_1 >= 20 OR HRS_WRK_D_CSWE >= 20) THEN 1
		ELSE 0
	END AS NDEEM17,
  -- NLIM_SSA is not used in the rest of this script
	CASE
		WHEN ISWEI = 1 AND WORK_PART_STATUS = 15 AND AGE > 12 AND AGE < 20 AND RELATIONSHIP_HOH IN (1,2) AND (SCHOOL_ATTENDENCE_HOP + SCHOOL_ATTENDENCE_EA + SCHOOL_ATTENDENCE_HOL) > 0 THEN 1
		ELSE 0
	END AS NLIM_SSA,
  -- NLIM_EDE is not used in the rest of this script
	CASE
		WHEN ISWEI = 1 AND AGE > 12 AND AGE < 20 AND RELATIONSHIP_HOH IN (1,2) AND (ED_NO_HIGH_SCHOOL_DIPL_HOP + ED_NO_HIGH_SCHOOL_DIPL_EA + ED_NO_HIGH_SCHOOL_DIPL_HOL) >= 20 THEN 1
		ELSE 0
	END AS NLIM_EDE
FROM
    a4;


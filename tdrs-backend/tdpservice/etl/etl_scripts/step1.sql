	*,
  -- NEXEMPT is not used in the rest of this script
	CASE
		WHEN ISWEI = 1 AND WORK_PART_STATUS >= 6 AND WORK_PART_STATUS <= 11 THEN 1
		ELSE 0
	END AS NEXEMPT,
  -- NDEEM15 means ____________________
	CASE
		WHEN ISWEI = 1 AND WORK_PART_STATUS = 15 AND AGE > 12 AND AGE < 20 AND RELATIONSHIP_HOH IN (1,2) AND (SCHOOL_ATTENDENCE_HOP + SCHOOL_ATTENDENCE_EA + SCHOOL_ATTENDENCE_HOL) > 0 THEN 1
		ELSE 0
	END AS NDEEM15,
  -- NDEEM16 means ____________________

CREATE OR REPLACE TEMPORARY VIEW a2 AS
SELECT
	*,
	CASE
		-- NWORK_ND means to meet the work requirement without deeming hours --
		WHEN ISWEI = 1 AND HRS_WRK_1 >= 20 AND THRS_WRK_1 >= 30 THEN 1
		ELSE 0
	END AS NWORK_ND,
	-- HWK_VOC and TWK_VOC mean ________________
	CASE
		WHEN ISWEI = 1 AND HRS_WRK_1 >= 20 AND THRS_WRK_1 >= 30 THEN HRS_WRK_1 - VOCATIONAL_ED_TRAINING_HOP - PROVIDE_CC_HOL - PROVIDE_CC_EA
		ELSE 0
	END AS HWK_VOC,
	CASE
		WHEN ISWEI = 1 AND HRS_WRK_1 >= 20 AND THRS_WRK_1 >= 30 THEN THRS_WRK_1 - VOCATIONAL_ED_TRAINING_HOP - PROVIDE_CC_HOL - PROVIDE_CC_EA
		ELSE 0
	END AS TWK_VOC,
	-- AF_NCORHRS is used later to deem hours if necassary, if CSWE hours are high enough --
  CASE
		WHEN ISWEI = 1 AND HRS_WRK_1 < 20 AND FLSA_STATE = 1 AND CSWE_HRS_1 > 0 AND CSWE_HRS_1 >= FLOOR((CASH_AMOUNT + CC_AMOUNT + OTHER_AMOUNT + TRANSITION_SERVICES_AMOUNT + TRANSP_AMOUNT + AMT_FOOD_STAMP_ASSISTANCE - CHILD_SUPPORT_AMT)/(5*MIN_WAGES)) THEN 20 - CSWE_HRS_1
		ELSE 0
	END AS AF_NCORHRS
FROM
  a1;


CREATE OR REPLACE TEMPORARY VIEW a3 AS
SELECT
	*,
	-- HRS_WRK_D_CSWE is core hours worked, with DEEMED hours from CSWE
	CASE
		WHEN ISWEI = 1 AND HRS_WRK_1 < 20 AND FLSA_STATE = 1 AND CSWE_HRS_1 > 0 AND CSWE_HRS_1 >= FLOOR((CASH_AMOUNT + CC_AMOUNT + OTHER_AMOUNT + TRANSITION_SERVICES_AMOUNT + TRANSP_AMOUNT + AMT_FOOD_STAMP_ASSISTANCE - CHILD_SUPPORT_AMT)/(5*MIN_WAGES)) THEN HRS_WRK_1 + AF_NCORHRS
		ELSE 0
	END AS HRS_WRK_D_CSWE,
	-- THRS_WRK_D_CSWE is total hours work, which is core and non-core hours together, with DEEMED hours from CSWE
	CASE
		WHEN ISWEI = 1 AND HRS_WRK_1 < 20 AND FLSA_STATE = 1 AND CSWE_HRS_1 > 0 AND CSWE_HRS_1 >= FLOOR((CASH_AMOUNT + CC_AMOUNT + OTHER_AMOUNT + TRANSITION_SERVICES_AMOUNT + TRANSP_AMOUNT + AMT_FOOD_STAMP_ASSISTANCE - CHILD_SUPPORT_AMT)/(5*MIN_WAGES)) THEN THRS_WRK_1 + AF_NCORHRS
		ELSE 0
	END AS THRS_WRK_D_CSWE
FROM
  a2;

CREATE OR REPLACE TEMPORARY VIEW a4 AS

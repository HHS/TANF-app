	CASE
		WHEN TPDABLE = 1 THEN 0
		WHEN TPWORK_ND = 1 OR TPWORK_D_CSWE = 1 OR TPWORK_DEEM_SATSCH_EDUDIR = 1 THEN 1
		ELSE 0
	END AS TPWORK,
  CASE
      WHEN ((P1_DEEM_SATSCH = 1 OR P1_DEEM_EDUDIR = 1) AND (P2_DEEM_SATSCH = 1 OR P2_DEEM_EDUDIR = 1)) OR ((P1_DEEM_SATSCH = 1 OR P1_DEEM_EDUDIR = 1 OR P2_DEEM_SATSCH = 1 OR P2_DEEM_EDUDIR = 1) AND (TPHRS_DEEM_SATSCH_EDUDIR >= TP_REQCORE AND TPTHRS_DEEM_SATSCH_EDUDIR >= TP_REQALL)) THEN 1
      ELSE 0
  END AS TPDEEM,
  CASE
      WHEN ((P1_DEEM_SATSCH = 1 OR P1_DEEM_EDUDIR = 1) AND (P2_DEEM_SATSCH = 1 OR P2_DEEM_EDUDIR = 1)) OR ((P1_DEEM_SATSCH = 1 OR P1_DEEM_EDUDIR = 1 OR P2_DEEM_SATSCH = 1 OR P2_DEEM_EDUDIR = 1) AND (TPHRS_DEEM_SATSCH_EDUDIR >= TP_REQCORE AND TPTHRS_DEEM_SATSCH_EDUDIR >= TP_REQALL)) THEN 1
      ELSE 0
  END AS TPLIMIT
FROM
  final_2p9;

--the following views are used to calculate the disregard variables--
CREATE OR REPLACE TEMPORARY VIEW final_2p11 AS
SELECT
  *,
	-- TPDCARD5 supercedes TPDCARD2, therefore we calculate it first --
	CASE
		WHEN TPDABLE = 1 THEN 0
		WHEN TPWORK = 1 AND (TPLIM_VOC = 1 OR TPLIMIT = 1) THEN 0
		WHEN (P1_WORK_PART_STATUS = 5 OR P2_WORK_PART_STATUS = 5) THEN 0
		WHEN TPNCP != 1 AND (P1_WORK_PART_STATUS = 7 OR P2_WORK_PART_STATUS = 7) THEN 0
		ELSE 0
	END AS TPDCARD5
FROM
	final_2p10;

CREATE OR REPLACE TEMPORARY VIEW final_2p12 AS
SELECT
	*,
	CASE
		-- If TPDCARD5 applies, then disregard TPDCARD2 --
		WHEN TPDCARD5 = 1 THEN 0
		WHEN TPDABLE = 1 THEN 0
		WHEN (P1_SANC = 1 OR P2_SANC = 1) THEN 1
		WHEN TPWORK = 1 AND (TPLIM_VOC = 1 OR TPLIMIT = 1) THEN 0
		WHEN TPNCP != 1 AND (P1_WORK_PART_STATUS = 7 OR P2_WORK_PART_STATUS = 7) THEN 0
		ELSE 0
	END AS TPDCARD2,
	-- TPDVEXEM is the domestic violence exception --
  CASE
    WHEN (TPWORK = 1 AND (P1_WORK_PART_STATUS = '09' OR P2_WORK_PART_STATUS = '09')) THEN 1
    ELSE 0
  END AS TPDVEXEM
FROM
	final_2p11;

CREATE OR REPLACE TEMPORARY VIEW final_2p AS
SELECT
	*,
	CASE
		WHEN TPWORK = 1 AND (TPDCARD2 = 1 OR TPDCARD5 = 1) AND TPDABLE = 1 THEN 1
		ELSE 0
	END AS TPDCRD_PART,
	-- calculating error flags

--if type_fam=2 and n_wei<2 then tperrfg='1';
--*if type_fam=2 and n_wei=1 then tperrfg='2';
--if (type_fam not eq 2)and ftype=2 then tperrfg='2';/*there are two parents in 2-p WPR*/;
--if (p1_wps = 1 or p2_wps = 1) then tperrfg='3';   /* TWO-PARENT FAMILY, NOT SINGLE CUSTODIAL PARENT FAMILY - ERROR */
--if (p1_sanc = 0 and p1_wps = 2) or (p2_wps = 2 and p2_sanc = 0) then tperrfg='4';


	CASE
		WHEN FAMILY_TYPE = 2 AND N_WEI< 2 THEN '1'
		WHEN FAMILY_TYPE != 2 AND FTYPE = 2 THEN '2'
		WHEN P1_WORK_PART_STATUS = 1 OR P2_WORK_PART_STATUS = 1 THEN '3'
		WHEN (P1_SANC = 0 AND P1_WORK_PART_STATUS = 2) OR (P2_SANC = 0 AND P2_WORK_PART_STATUS = 2) THEN '4'
		ELSE '  '
	END AS TPERRFG
FROM
  final_2p12;



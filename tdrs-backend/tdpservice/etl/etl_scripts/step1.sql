		WHEN FTYPE IN (1,2) AND AF_WORK_PART_STATUS = 17 AND YOUNGEST > 6 THEN '06'
		WHEN FTYPE IN (1,2) AND AF_WORK_PART_STATUS = 9 AND AF_WEI >= 1 AND AF_WEI <= 5 AND FIPS_CODE NOT IN (6, 23, 21, 27, 39) THEN '08'

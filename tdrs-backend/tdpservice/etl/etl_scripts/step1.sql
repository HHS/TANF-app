CREATE OR REPLACE TEMPORARY VIEW adult2 AS
SELECT
  *,
  -- If an adult is an WEI, calculate the following variables --
  -- Holiday hours (which cap at 6) --
  CASE
    WHEN ISWEI = 0 THEN 0
    WHEN WORK_EXPERIENCE_HOL + JOB_SEARCH_HOL + COMM_SERVICES_HOL + VOCATIONAL_ED_TRAINING_HOL + PROVIDE_CC_HOL > 6 THEN 6
    ELSE WORK_EXPERIENCE_HOL + JOB_SEARCH_HOL + COMM_SERVICES_HOL + VOCATIONAL_ED_TRAINING_HOL + PROVIDE_CC_HOL
  END AS SUM_CORE_HOLI,
  CASE
    WHEN ISWEI = 0 THEN 0
    WHEN JOB_SKILLS_TRAINING_HOL + ED_NO_HIGH_SCHOOL_DIPL_HOL + SCHOOL_ATTENDENCE_HOL > 6 THEN 6
    ELSE JOB_SKILLS_TRAINING_HOL + ED_NO_HIGH_SCHOOL_DIPL_HOL + SCHOOL_ATTENDENCE_HOL
  END AS SUM_NON_CORE_HOLI,
  CASE
    WHEN ISWEI = 0 THEN 0
    WHEN WORK_EXPERIENCE_HOL + COMM_SERVICES_HOL > 6 THEN 6
    ELSE WORK_EXPERIENCE_HOL + COMM_SERVICES_HOL
  END AS SUM_CSWE_HOLI,
  -- Exab hours (which cap at 4) --
  CASE
    WHEN ISWEI = 0 THEN 0
    WHEN WORK_EXPERIENCE_EA + JOB_SEARCH_EA + COMM_SERVICES_EA + VOCATIONAL_ED_TRAINING_EA + PROVIDE_CC_EA > 4 THEN 4
    ELSE WORK_EXPERIENCE_EA + JOB_SEARCH_EA + COMM_SERVICES_EA + VOCATIONAL_ED_TRAINING_EA + PROVIDE_CC_EA
  END AS SUM_CORE_EXAB,
  CASE
    WHEN ISWEI = 0 THEN 0
    WHEN JOB_SKILLS_TRAINING_EA + ED_NO_HIGH_SCHOOL_DIPL_EA + SCHOOL_ATTENDENCE_EA > 4 THEN 4
    ELSE JOB_SKILLS_TRAINING_EA + ED_NO_HIGH_SCHOOL_DIPL_EA + SCHOOL_ATTENDENCE_EA
  END AS SUM_NON_CORE_EXAB,
  CASE
    WHEN ISWEI = 0 THEN 0
    WHEN WORK_EXPERIENCE_EA + COMM_SERVICES_EA > 4 THEN 4
    ELSE WORK_EXPERIENCE_EA + COMM_SERVICES_EA
  END AS SUM_CSWE_EXAB,
  -- These WEI variables determine if a person counts as a WEI using different types of hours (work, holiday, or exab)
  CASE
    WHEN (UNSUB_EMPLOYMENT + SUB_PRIVATE_EMPLOYMENT + SUB_PUBLIC_EMPLOYMENT + WORK_EXPERIENCE_HOP + OJT + JOB_SEARCH_HOP + COMM_SERVICES_HOP + VOCATIONAL_ED_TRAINING_HOP + JOB_SKILLS_TRAINING_HOP + ED_NO_HIGH_SCHOOL_DIPL_HOP + SCHOOL_ATTENDENCE_HOP + PROVIDE_CC_HOP + OTHER_WORK_ACTIVITIES) > 0 THEN 1
    ELSE 0
  END AS WRK_WEI,
  CASE
    WHEN (WORK_EXPERIENCE_HOL + JOB_SEARCH_HOL + COMM_SERVICES_HOL + VOCATIONAL_ED_TRAINING_HOL + JOB_SKILLS_TRAINING_HOL + ED_NO_HIGH_SCHOOL_DIPL_HOL + SCHOOL_ATTENDENCE_HOL + PROVIDE_CC_HOL) > 0 THEN 1
    ELSE 0
  END AS HOL_WEI,
  CASE
    WHEN (WORK_EXPERIENCE_EA + JOB_SEARCH_EA + COMM_SERVICES_EA + VOCATIONAL_ED_TRAINING_EA + JOB_SKILLS_TRAINING_EA + ED_NO_HIGH_SCHOOL_DIPL_EA + SCHOOL_ATTENDENCE_EA + PROVIDE_CC_EA) > 0 THEN 1
    ELSE 0
  END AS EXA_WEI,
  -- NDISABLE means a person is disabled and is used for error flags later --
  CASE
    WHEN (RECEIVE_SSI = 1 AND UNEARNED_SSI > 0) OR AID_AGED_BLIND = 1 OR FED_OASDI_PROGRAM = 1 THEN 1
    ELSE 0
  END AS NDISABLE
FROM
  adult1;

CREATE OR REPLACE TEMPORARY VIEW adult AS
SELECT
  *,
  CASE
    WHEN (WRK_WEI = 1) OR (HOL_WEI = 1) OR (EXA_WEI = 1) THEN 1
    ELSE 0
  END AS WKHLEA_WEI,
  -- Hours worked --
  WORK_EXPERIENCE_HOP + COMM_SERVICES_HOP + SUM_CSWE_HOLI + SUM_CSWE_EXAB as CSWE_HRS_1,
  UNSUB_EMPLOYMENT + SUB_PRIVATE_EMPLOYMENT + SUB_PUBLIC_EMPLOYMENT + WORK_EXPERIENCE_HOP + OJT + JOB_SEARCH_HOP + COMM_SERVICES_HOP + VOCATIONAL_ED_TRAINING_HOP + PROVIDE_CC_HOP + SUM_CORE_HOLI + SUM_CORE_EXAB as HRS_WRK_1,
  -- Other hours worked --
  JOB_SKILLS_TRAINING_HOP + ED_NO_HIGH_SCHOOL_DIPL_HOP + SCHOOL_ATTENDENCE_HOP + SUM_NON_CORE_HOLI + SUM_NON_CORE_EXAB as OHRS_WRK_1,
  -- Total hours worked --
  UNSUB_EMPLOYMENT + SUB_PRIVATE_EMPLOYMENT + SUB_PUBLIC_EMPLOYMENT + WORK_EXPERIENCE_HOP + OJT + JOB_SEARCH_HOP + COMM_SERVICES_HOP + VOCATIONAL_ED_TRAINING_HOP + PROVIDE_CC_HOP + SUM_CORE_HOLI + SUM_CORE_EXAB + JOB_SKILLS_TRAINING_HOP + ED_NO_HIGH_SCHOOL_DIPL_HOP + SCHOOL_ATTENDENCE_HOP + SUM_NON_CORE_HOLI + SUM_NON_CORE_EXAB as THRS_WRK_1
FROM
  adult2;



		WHEN (P2_WORK_PART_STATUS = 2) AND ((P2_FAMILY_AFFILIATION = 1 AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0) OR (P2_FAMILY_AFFILIATION = 2 AND WORK_REQ_SANCTION = 1 AND SANC_REDUCTION_AMT > 0 AND P2_WEI = 2)) THEN 1
		ELSE 0
	END AS P2_SANC,
	-- P1_SATSCH and P2_SATSCH are "school satisfactory", which can be used to deem a minimum of 20 hours later
